export function getTheme(id: string): ThemePreset | undefined {
  return THEMES.find((theme) => theme.id === id);
}

export function themeToStyleRecord(theme: ThemePreset): Record<string, string> {
  const style: Record<string, string> = {};
  (Object.keys(CSS_VAR_MAP) as (keyof ThemeTokens)[]).forEach((key) => {
    const value = theme.tokens[key];
    if (value !== undefined) {
      style[CSS_VAR_MAP[key]] = value;
    }
  });
  return style;
}

export function applyTheme(id: string): void {
  if (typeof document === 'undefined') return;
  const theme = getTheme(id);
  if (!theme) return;
  const style = themeToStyleRecord(theme);
  for (const [k, v] of Object.entries(style)) {
    document.documentElement.style.setProperty(k, v);
  }
  document.documentElement.dataset.theme = id;
}
